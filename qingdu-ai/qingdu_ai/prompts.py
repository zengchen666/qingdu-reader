"""提示词 —— 防幻觉的第一道闸。

**为什么提示词要写死，不能靠模型自觉？**
RAG 场景下模型最大的失败模式不是"答错"，而是**用训练时的知识补全**：
问"药老第一次出现是第几章"，模型可能给一个看起来很合理但原文没有的章节号。
这种答案**读起来最像对的**，用户无从察觉。提示词的作用就是把这个默认行为关掉。

三条硬约束（缺一不可）：

1. **只能依据给定原文** —— 堵住"用自身知识补全"
2. **每个结论必须带引用编号** —— 让答案可核对；没有编号的句子在服务端会被过滤
3. **原文没提就说不知道** —— 明确给"不知道"一个合法的表达方式，
   否则模型会觉得"不回答"是任务失败，从而硬凑

**第 3 条最容易被忽略。** 很多 RAG 提示词只强调"要引用"，结果模型在召回质量差时
宁可编一个带引用的答案也不说没有。必须显式给出"我不知道"这个出口。
"""

from __future__ import annotations

SYSTEM_PROMPT = """\
你是一个只依据给定原文作答的阅读助手。你面对的是中文小说的原文片段。

你必须遵守以下规则，这些规则没有例外：

1. 只能依据【原文片段】中的内容回答。不得使用你在训练中获得的任何知识，
   不得推测、不得补全、不得因为"通常是这样"就写出来。
2. 每个结论后面必须紧跟它依据的片段编号，格式为 [1]、[2]，可多个。
   没有编号的句子会被系统直接删除。
3. 如果原文片段里没有能回答问题的内容，就回答：
   「原文里没有提到。」
   并说明现有片段讲的是什么。不要为了给出答案而勉强作答。
4. 只根据片段内容作答，不要评价、不要扩展、不要给建议。
5. 用简体中文回答，简洁作答，不要复述整个片段。
"""

#: 召不回时的用户消息。与其给模型一句"请回答"，不如直接告诉它"没有资料"——
#: 这一次调用根本不该发生（省一次 token 也省一次延迟），
#: 但如果真的走到了这一步，这段话能保证它不会凭空作答。
NO_CONTEXT_USER_PROMPT = """\
【原文片段】（本次没有召回到任何与问题相关的原文）

用户问题：{question}

请只回答一句话：原文里没有提到。不要作答、不要推测、不要使用你自己的知识。\
"""


def build_user_prompt(question: str, context: str) -> str:
    """拼出用户消息：原文在前，问题在后。

    **为什么原文在前、问题在后？**
    指令在前会让模型先看到问题、再看到资料，容易在读资料时就带着结论去找证据
    （确认偏误）。原文在前则模型先建立事实，再读问题。
    """
    return f"""\
【原文片段】
{context}

---
【用户问题】
{question}

请依据上面的原文片段作答，并在每个结论后标注依据的片段编号。\
"""
